using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace GeneratedMapper.Generator;

// Turns the resolved MappingModel list into the single GeneratedMappings.g.cs source file.
// Split across four partial-class files by responsibility (this file is orchestration only):
//   - MappingEmitter.Imperative.cs  - the To{Dest}() extension methods.
//   - MappingEmitter.Projection.cs  - the ProjectTo{Dest}() IQueryable extension methods.
//   - MappingEmitter.Dispatcher.cs  - the runtime type-keyed dispatcher and IMapper service.
// A MappingModel reaching this class is otherwise assumed emittable - the one remaining
// whole-mapping rejection (GM006, below) is checked here because it depends on interaction
// between two fields (DestinationIsInitOnly and DestinationHasParameterlessConstructor) that
// only matters at emission time, not during per-property resolution.
internal static partial class MappingEmitter
{
    public static string Emit(
        IReadOnlyCollection<MappingModel> mappings,
        bool useFrozenDictionary,
        Action<Diagnostic>? report = null)
    {
        var validMappings = new List<MappingModel>();

        foreach (var mapping in mappings)
        {
            // A destination with an init-only property but no parameterless constructor can't
            // be built at all: not via sequential assignment (init setters forbid that outside
            // the constructor call), and not via object-initializer syntax either (a positional
            // record's constructor parameters are required, so `new Dest { Prop = x }` alone
            // won't compile). The whole mapping is skipped rather than emitting code that can't
            // build. Closing this gap would mean matching constructor parameters to settable
            // properties by name/type instead of skipping - not implemented yet.
            if (HasInitOnlyProperty(mapping) && !mapping.DestinationHasParameterlessConstructor)
            {
                report?.Invoke(Diagnostic.Create(
                    Diagnostics.NoParameterlessConstructor,
                    Location.None,
                    mapping.Source.DisplayName,
                    mapping.Destination.DisplayName));
                continue;
            }

            validMappings.Add(mapping);
        }

        // Keyed lookup used by MappingEmitter.Projection.cs to inline a nested/element type's
        // own projection expression rather than calling a method (SQL projection expressions
        // can't contain arbitrary method calls and still translate to SQL).
        var byPair = validMappings.ToDictionary(m => (m.Source.FullyQualifiedName, m.Destination.FullyQualifiedName));

        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        if (useFrozenDictionary)
            sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Linq.Expressions;");
        sb.AppendLine();
        sb.AppendLine("namespace GeneratedMapper;");
        sb.AppendLine();
        sb.AppendLine("public static class GeneratedMappings");
        sb.AppendLine("{");

        foreach (var mapping in validMappings)
            EmitMapping(sb, mapping, report);

        foreach (var mapping in validMappings)
            EmitProjection(sb, mapping, byPair, report);

        EmitGenericDispatcher(sb, validMappings, useFrozenDictionary);

        sb.AppendLine("}");
        sb.AppendLine();

        EmitMapperService(sb, validMappings);

        return sb.ToString();
    }

    private static bool HasInitOnlyProperty(MappingModel mapping)
        => mapping.Properties.Any(p => p.DestinationIsInitOnly);

    private static string MaterializeCall(CollectionShape shape)
        => shape switch
        {
            CollectionShape.Array => "ToArray()",
            CollectionShape.HashSet => "ToHashSet()",
            _ => "ToList()"
        };
}
